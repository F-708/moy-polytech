    private val normalizeCache = java.util.concurrent.ConcurrentHashMap<String, String>()

    fun normalize(rawTitle: String): String = normalizeCache.getOrPut(rawTitle) { normalizeUncached(rawTitle) }

    private fun normalizeUncached(rawTitle: String): String {
        val cleaned = cleanRawTitle(rawTitle)
        if (cleaned.isBlank()) return rawTitle.trim()

        MPK_SCHEDULE_ABBREVIATIONS[cleaned]?.let { return it }
        for ((abbr, full) in MPK_SCHEDULE_ABBREVIATIONS) {
            if (cleaned.equals(abbr, ignoreCase = true)) {
                return full
            }
        }

        MpkCurriculum.ALL_SUBJECTS.firstOrNull { it.equals(cleaned, ignoreCase = true) }?.let {
            return it
        }

        val cleanedWithoutParens = cleaned.replace(Regex("\\(.*\\)"), "").trim()
        MpkCurriculum.ALL_SUBJECTS
            .firstOrNull {
                it.replace(Regex("\\(.*\\)"), "").trim().equals(cleanedWithoutParens, ignoreCase = true)
            }?.let {
                return it
            }

        var bestMatch: String? = null
        var bestScore = 0.0

        for (officialSubject in MpkCurriculum.ALL_SUBJECTS) {
            val score = calculateSimilarity(cleaned.lowercase(Locale.ROOT), officialSubject.lowercase(Locale.ROOT))
            if (score > bestScore) {
                bestScore = score
                bestMatch = officialSubject
            }
        }

        if (bestScore >= 0.60 && bestMatch != null) {
            return bestMatch
        }

        return cleaned
    }

    private val shortNameEntries by lazy {
        PREDEFINED_SHORT_NAMES.entries
            .sortedByDescending { it.key.length }
            .map { it.value to it.key.lowercase(Locale.ROOT) }
    }
    private val acronymEntries by lazy {
        PREDEFINED_ACRONYMS.entries
            .sortedByDescending { it.key.length }
            .map { it.value to it.key.lowercase(Locale.ROOT) }
    }

    private fun containsPhraseBounded(
        textLower: String,
        phraseLower: String,
    ): Boolean {
        if (phraseLower.isEmpty()) return false
        var from = 0
        while (true) {
            val idx = textLower.indexOf(phraseLower, from)
            if (idx < 0) return false
            val beforeOk = idx == 0 || !textLower[idx - 1].isLetterOrDigit()
            val end = idx + phraseLower.length
            val afterOk = end >= textLower.length || !textLower[end].isLetterOrDigit()
            if (beforeOk && afterOk) return true
            from = idx + 1
        }
    }

    fun getShortName(rawTitle: String): String {
        val normalized = normalize(rawTitle)

        if (normalized.isBlank() || normalized.all { it.isDigit() }) return ""

        SubjectRenameStore.customNameCached(normalized)?.let { return SubjectRenameStore.RENAMED_PREFIX + it }

        PREDEFINED_SHORT_NAMES[normalized]?.let { return it }

        val normalizedLower = normalized.lowercase(Locale.ROOT)
        for ((shortVal, keyLower) in shortNameEntries) {
            if (containsPhraseBounded(normalizedLower, keyLower)) {
                return shortVal
            }
        }

        return normalized
    }

    fun getAcronym(rawTitle: String): String {
        val normalized = normalize(rawTitle)

        PREDEFINED_ACRONYMS[normalized]?.let { return it }

        val normalizedLower = normalized.lowercase(Locale.ROOT)
        for ((acronym, keyLower) in acronymEntries) {
            if (containsPhraseBounded(normalizedLower, keyLower)) {
                return acronym
            }
        }

        val words =
            normalized
                .replace(Regex("[^a-zA-Z\\u0400-\\u04FF0-9\\s]"), " ")
                .split(Regex("\\s+"))
                .filter { it.isNotBlank() && !STOP_WORDS.contains(it.lowercase(Locale.ROOT)) }

        return when {
            words.isEmpty() -> normalized.take(3).uppercase(Locale.ROOT)
            words.size == 1 -> {
                val single = words.first()
                if (single.length <= 4) {
                    single.uppercase(Locale.ROOT)
                } else {
                    single.take(3).uppercase(Locale.ROOT)
                }
            }
            words.size in 2..4 -> {
                words.map { it.first().uppercaseChar() }.joinToString("")
            }
            else -> {
                words.take(4).map { it.first().uppercaseChar() }.joinToString("")
            }
        }
    }

    fun levenshteinSimilarity(
        a: String,
        b: String,
    ): Double {
        if (a.isEmpty() || b.isEmpty()) return 0.0
        val s1 = a.lowercase(Locale.ROOT)
        val s2 = b.lowercase(Locale.ROOT)
        if (s1 == s2) return 1.0
        val maxLen = max(s1.length, s2.length)
        return 1.0 - (levenshteinDistance(s1, s2).toDouble() / maxLen)
    }

    private fun cleanRawTitle(raw: String): String {
        var text = raw.trim()

        val nbStart = "(?<![0-9A-Za-z_\\u0400-\\u04FF])"
        val nbEnd = "(?![0-9A-Za-z_\\u0400-\\u04FF])"

        text = text.replace(Regex("(?i)$nbStart(ауд|каб)$nbEnd\\.?\\s*\\d+[\\u0430-\\u044Fa-z]?"), "")

        text = text.replace(Regex("(?i)$nbStart(лек|лекц|лекция|пр|практ|практика|лаб|лабор|зач|экз|ауд|каб)$nbEnd\\.?"), "")

        text = text.replace(Regex("(?i)$nbStart(1|2)\\s*п/?г$nbEnd"), "")
        text = text.replace(Regex("(?i)\\((1|2)\\s*п/?г\\)"), "")
        text = text.replace(Regex("(?i)\\[(1|2)\\s*п/?г\\]"), "")
        text = text.replace(Regex("(?i)${nbStart}п/?г\\s*(1|2)$nbEnd"), "")

        text = text.replace(Regex("\\s+\\d{2,3}[\\u0430-\\u044Fa-z]?$nbEnd"), "")
        text = text.replace(Regex("\\s+"), " ")
        text = text.trim(',', '.', '-', ' ', '/', '\\')

        return text
    }

    private fun calculateSimilarity(
        s1: String,
        s2: String,
    ): Double {
        if (s1 == s2) return 1.0
        if (s1.isEmpty() || s2.isEmpty()) return 0.0

        val maxLen = max(s1.length, s2.length)
        val distance = levenshteinDistance(s1, s2)
        val levScore = 1.0 - (distance.toDouble() / maxLen)

        val tokens1 = s1.split(Regex("\\s+")).filter { it.length > 2 }.toSet()
        val tokens2 = s2.split(Regex("\\s+")).filter { it.length > 2 }.toSet()

        if (tokens1.isEmpty() || tokens2.isEmpty()) return levScore

        val intersection = tokens1.intersect(tokens2).size
        val union = tokens1.union(tokens2).size
        val jaccardScore = if (union > 0) intersection.toDouble() / union else 0.0

        return (levScore * 0.5) + (jaccardScore * 0.5)
    }

    private fun levenshteinDistance(
        s1: String,
        s2: String,
    ): Int {
        val dp = Array(s1.length + 1) { IntArray(s2.length + 1) }

        for (i in 0..s1.length) dp[i][0] = i
        for (j in 0..s2.length) dp[0][j] = j

        for (i in 1..s1.length) {
            for (j in 1..s2.length) {
                val cost = if (s1[i - 1] == s2[j - 1]) 0 else 1
                dp[i][j] =
                    min(
                        dp[i - 1][j] + 1,
                        min(
                            dp[i][j - 1] + 1,
                            dp[i - 1][j - 1] + cost,
                        ),
                    )
            }
        }

        return dp[s1.length][s2.length]
    }
